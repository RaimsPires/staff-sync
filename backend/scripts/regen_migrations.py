"""Dev helper: rebuild the migration chain from the models while the schema is still settling.

0000 (extensions) and 0002 (RLS + grants) are hand-written; 0001 is autogenerated against an empty DB.
Run:  .venv/bin/python scripts/regen_migrations.py
"""

import asyncio
import glob
import os
import subprocess
import sys

import asyncpg

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V = os.path.join(ROOT, "src/staffsync/migrations/versions")
SCRATCH = "staffsync_migrate_scratch"


async def scratch_db(drop_only=False):
    c = await asyncpg.connect("postgresql://staffsync:staffsync@localhost:5433/postgres")
    await c.execute(f"DROP DATABASE IF EXISTS {SCRATCH} WITH (FORCE)")
    if not drop_only:
        await c.execute(f"CREATE DATABASE {SCRATCH}")
    await c.close()


def alembic(*args):
    env = {**os.environ, "MIGRATION_DATABASE_URL": f"postgresql+asyncpg://staffsync:staffsync@localhost:5433/{SCRATCH}"}
    subprocess.run([sys.executable, "-m", "alembic", *args], cwd=ROOT, env=env, check=True)


asyncio.run(scratch_db())
for f in glob.glob(f"{V}/*_initial_schema.py"):
    os.remove(f)
sec = glob.glob(f"{V}/*_0002_tenant_security.py")[0]
os.rename(sec, sec + ".hold")  # the chain must be unbroken while autogenerating 0001
try:
    alembic("upgrade", "0000")
    alembic("revision", "--autogenerate", "-m", "initial schema", "--rev-id", "0001", "--head", "0000")
finally:
    os.rename(sec + ".hold", sec)
alembic("upgrade", "head")  # proves the whole chain applies
asyncio.run(scratch_db(drop_only=True))
print("migrations regenerated")
